/*
Task
- Read 3 numbers from stdin and print their sum to stdout.
- One line that contains  space-separated integers: a, b, and c.
*/

#include <iostream>

using namespace std;


int main() {
       int a, b, c;
       cin >> a >> b >> c;
       int d = a+b+c;
       cout << d << endl;
        
    return 0;
}
